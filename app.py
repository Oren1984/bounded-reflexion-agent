"""Local demo UI:  streamlit run app.py

A thin presentation layer over the same run records the CLI prints. It contains no
workflow logic of its own.
"""

import os

import streamlit as st
from dotenv import load_dotenv

from bounded_reflexion.agent import DEFAULT_MODEL
from bounded_reflexion.attacks import ATTACKS, classify
from bounded_reflexion.demo import SCENARIOS, run_scenario
from bounded_reflexion.graph import run_task
from bounded_reflexion.runner import docker_available
from bounded_reflexion.state import CONFIGS, MAX_REPAIRS, list_tasks, load_task
from bounded_reflexion.tracing import MOCK_NOTICE, build_mock_trace, render_mock_trace

load_dotenv()
st.set_page_config(page_title="Bounded Reflexion Agent", layout="wide")

STATUS_TEXT = {
    "passed": ("PASSED", "green"),
    "failed": ("FAILED", "red"),
    "failed_retry_limit": ("FAILED - retry limit reached", "red"),
    "blocked_policy": ("BLOCKED by policy", "orange"),
    "timeout": ("STOPPED - execution timeout", "red"),
    "evaluator_error": ("STOPPED - evaluator error", "red"),
}
MOCK, LIVE = "Demo / Mock Mode", "Live model"


def flow(record: dict) -> str:
    """The path this run took, e.g. Generate -> Boundary -> Test (FAIL) -> Reflect -> ..."""
    names = []
    for event in record["events"]:
        node = event["node"]
        if node == "generate":
            names.append("Generate" if event["kind"] == "initial" else "Repair")
        elif node == "boundary":
            names.append(f"Boundary check ({event['decision'].upper()})")
        elif node == "execute":
            names.append(f"Test ({'PASS' if event['passed'] else 'FAIL'})")
        elif node == "reflect":
            names.append("Reflect")
        else:
            names.append(STATUS_TEXT[event["status"]][0])
    return "  →  ".join(["Task"] + names)


def show(record: dict) -> None:
    label, colour = STATUS_TEXT[record["status"]]
    if record["mode"] == "mock":
        st.warning(
            f"**{MOCK}** - model replies are scripted sample responses, not live model output. "
            "The workflow, policy checks and sandboxed pytest runs are real."
        )
    else:
        st.info(f"**Live mode** - replies generated by `{os.getenv('BRA_MODEL', DEFAULT_MODEL)}`.")

    st.subheader(f":{colour}[{label}]")
    a, b, c, d = st.columns(4)
    a.metric("Task", record["task_id"])
    b.metric("Attempts", record["attempts"])
    c.metric("Repairs used", f"{record['repairs_used']} / {record['max_repairs']}")
    d.metric("Execution time", f"{record['duration_s']} s")
    st.markdown(f"**Workflow:** {flow(record)}")

    task = load_task(record["task_id"])
    with st.expander("Task given to the agent", expanded=bool(record["attack"])):
        st.markdown(task.prompt)
        if record["attack"]:
            attack = ATTACKS[record["attack"]]
            st.error(f"Injected content (simulated attack `{attack.id}` - goal: {attack.goal}):")
            st.code(attack.render(task.id), language="text", wrap_lines=True)

    reflections = record["reflections"]
    for index, entry in enumerate(record["history"]):
        kind = "initial attempt" if entry["attempt"] == 1 else f"repair {entry['attempt'] - 1}"
        st.markdown(f"#### Attempt {entry['attempt']} of {1 + record['max_repairs']} ({kind})")
        left, right = st.columns(2)
        with left:
            st.caption("Generated solution")
            for path, content in entry["files"].items():
                if path != "solution.py":
                    st.caption(f"Additional file the model tried to write: `{path}`")
                st.code(content, language="python", wrap_lines=True)
            if not entry["files"]:
                st.code("(no file block in the model reply)")
        with right:
            st.caption("Boundary check")
            if entry["violations"]:
                st.error("BLOCKED - not executed\n\n" + "\n".join(
                    f"- `{v['rule']}`: {v['detail']}" for v in entry["violations"]
                ))
            else:
                st.success("Allowed")
            feedback = entry["feedback"]
            if feedback:
                st.caption("pytest result (protected tests, Docker sandbox)")
                verdict = "PASS" if feedback["passed"] else f"FAIL ({feedback['failure_type']})"
                st.markdown(f"**{verdict}** - {feedback['summary']} - {feedback['duration_s']} s")
                failures = [
                    f"{f['test']}: {f['message'].strip().splitlines()[0]}"
                    for f in feedback["failures"]
                ]
                if failures:
                    st.code("\n".join(failures[:4]), language="text", wrap_lines=True)
                if len(failures) > 4:
                    with st.expander(f"All {len(failures)} failures"):
                        st.code("\n".join(failures), language="text", wrap_lines=True)
        if index < len(reflections):
            st.info(f"**Reflection after attempt {entry['attempt']}:** {reflections[index]}")

    if record["attack"]:
        st.markdown(f"#### Security outcome: `{classify(record)}`")
    if record["status"] == "failed_retry_limit":
        st.markdown(
            f"The workflow stopped because the limit of **{MAX_REPAIRS} repair iterations** "
            "was reached. The limit is a routing rule in the graph, not a prompt instruction."
        )
    st.markdown("#### Trace")
    if record["trace_url"]:
        st.markdown(f"[Open LangSmith trace]({record['trace_url']})")
    trace = build_mock_trace(record)
    st.warning(f"**Mock / Demo tracing** - {MOCK_NOTICE.split(' - ', 1)[1]}")
    st.caption(
        "This is the run tree a LangSmith trace of this run would contain: the workflow run "
        "with its tags and metadata, one child run per stage, and the model calls and "
        "sandbox execution beneath them."
    )
    st.code(render_mock_trace(trace), language="text")
    with st.expander("Mock trace as JSON"):
        st.json(trace)
    with st.expander("Local event trace (audit log)"):
        st.json(record["events"])


st.title("Bounded Reflexion Agent")
st.caption("Generate → Test → Reflect → Repair → Re-test, inside explicit boundaries. POC demo.")

has_key = bool(os.getenv("ANTHROPIC_API_KEY"))
with st.sidebar:
    mode = st.radio("Mode", [MOCK, LIVE] if has_key else [MOCK])
    if not has_key:
        st.caption("Live mode needs ANTHROPIC_API_KEY in .env.")
    if mode == MOCK:
        scenario = st.selectbox(
            "Scenario", list(SCENARIOS), format_func=lambda s: SCENARIOS[s].title
        )
    else:
        task_id = st.selectbox("Task", list_tasks())
        config_name = st.selectbox("Configuration", list(CONFIGS), index=2)
        attack_id = st.selectbox("Injected attack (optional)", [None, *ATTACKS])
    start = st.button("Run", type="primary")

if start:
    if not docker_available():
        st.error("Docker is not running. Generated code is only ever executed in the sandbox.")
        st.stop()
    with st.spinner("Running workflow..."):
        if mode == MOCK:
            st.session_state.record = run_scenario(scenario)
        else:
            from bounded_reflexion.agent import make_model

            st.session_state.record = run_task(
                load_task(task_id), CONFIGS[config_name], make_model(),
                attack=ATTACKS[attack_id] if attack_id else None,
            )

if "record" in st.session_state:
    show(st.session_state.record)
else:
    st.write("Choose a scenario in the sidebar and press **Run**.")
